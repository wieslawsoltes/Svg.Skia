#!/usr/bin/env python3
"""Generate checked MCP reference pages from the companion's executable catalog."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess
from typing import Any


def cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def constraints(schema: dict[str, Any]) -> str:
    pieces: list[str] = []
    if "enum" in schema:
        pieces.append("Values: " + ", ".join(f"`{value}`" for value in schema["enum"]))
    for key, label in (("minimum", "minimum"), ("maximum", "maximum"),
                       ("minLength", "minimum characters"), ("maxLength", "maximum characters"),
                       ("minItems", "minimum items"), ("maxItems", "maximum items"),
                       ("maxProperties", "maximum fields")):
        if key in schema:
            pieces.append(f"{label}: {schema[key]}")
    if "items" in schema:
        item = schema["items"]
        kind = item.get("type", "value")
        pieces.append(f"item type: {kind}")
    if schema.get("additionalProperties") is False:
        pieces.append("unknown fields rejected")
    return "; ".join(pieces)


def reference(tools: list[dict[str, Any]], guide: str) -> str:
    lines = ["# UnoDraw MCP tool reference", "",
             f"This reference contains all **{len(tools)} tools** from the executable catalog.",
             "It is generated by `scripts/generate_unodraw_mcp_docs.py`; update the C# catalog",
             "and regenerate this page when an input schema changes.", "",
             f"See the [connection and workflow guide]({guide}) for desktop/browser setup,",
             "resources, prompts, document identities, revision checks, export content blocks,",
             "read-only mode, cancellation and troubleshooting.", "",
             "All calls use MCP `tools/call` with the listed tool name and an `arguments` object.",
             "Names and enum values are case-sensitive. Required fields below describe the schema;",
             "action-specific operations can require additional fields described by the tool.",
             "Complete nested schemas follow each argument table. Mixed read/write tools require",
             "an editing connection even when invoked with a read action.", "",
             "## Index", "", "| Tool | Access | Purpose |", "| --- | --- | --- |"]
    for tool in tools:
        access = "Inspection/export" if tool["annotations"]["readOnlyHint"] else "Editing"
        name = tool["name"]
        lines.append(f"| [`{name}`](#{name}) | {access} | {cell(tool['description'])} |")
    for tool in tools:
        name, schema = tool["name"], tool["inputSchema"]
        required = set(schema.get("required", []))
        annotations = tool["annotations"]
        lines.extend(["", f"## `{name}`", "", tool["description"], "",
                      "**Access:** " + ("inspection/export connection permitted." if annotations["readOnlyHint"] else "editing connection required."), "",
                      "| Argument | Type | Required | Meaning and bounds |", "| --- | --- | --- | --- |"])
        for field, definition in schema.get("properties", {}).items():
            kind = definition.get("type", "any")
            if isinstance(kind, list):
                kind = " or ".join(kind)
            meaning = definition.get("description", "")
            limits = constraints(definition)
            if limits:
                meaning += (" " if meaning else "") + limits + "."
            lines.append(f"| `{field}` | `{kind}` | {'Yes' if field in required else 'No'} | {cell(meaning)} |")
        lines.extend(["", "### Input schema", "", "```json", json.dumps(schema, indent=2, ensure_ascii=False), "```"])
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bridge", type=Path, required=True, help="Compiled UnoDraw.Mcp.dll")
    parser.add_argument("--dotnet", default="dotnet")
    parser.add_argument("--check", action="store_true", help="Fail instead of rewriting stale pages")
    arguments = parser.parse_args()
    repo = Path(__file__).resolve().parents[1]
    process = subprocess.run([arguments.dotnet, str(arguments.bridge.resolve()), "--describe"],
                             check=True, capture_output=True, text=True, timeout=30)
    tools = json.loads(process.stdout)
    if not isinstance(tools, list) or not tools or len({tool["name"] for tool in tools}) != len(tools):
        raise ValueError("The executable returned an empty or invalid tool catalog")
    tools.sort(key=lambda tool: tool["name"])
    guide = (repo / "docs/unodraw-mcp.md").read_text()
    site_guide = guide.replace("(unodraw-mcp-tools.md)", "(mcp-tools)")
    for name in ("unodraw.md", "unodraw-editor-theme.md"):
        site_guide = site_guide.replace(f"({name})", f"(https://github.com/wieslawsoltes/Svg.Skia/blob/master/docs/{name})")
    outputs = {
        repo / "docs/unodraw-mcp-tools.md": reference(tools, "unodraw-mcp.md"),
        repo / "site/articles/editor/mcp-tools.md": '---\ntitle: "MCP Tool Reference"\n---\n\n' + reference(tools, "mcp"),
        repo / "site/articles/editor/mcp.md": '---\ntitle: "UnoDraw MCP"\n---\n\n' + site_guide,
    }
    stale = []
    for path, content in outputs.items():
        if path.exists() and path.read_text() == content:
            continue
        if arguments.check:
            stale.append(str(path.relative_to(repo)))
        else:
            path.write_text(content)
    if stale:
        parser.error("Regenerate MCP documentation: " + ", ".join(stale))
    print(f"{'Verified' if arguments.check else 'Generated'} {len(outputs)} pages for {len(tools)} tools.")


if __name__ == "__main__":
    main()
